#!/usr/bin/env python3
"""Converts the C++ overlay's generated tables (game_names_data.inc and
player_icons_data.inc, both made from data.cdb) into src/fo/data/GameTables.hx.

    python3 -I tools/gen_tables.py ../repo/src/farever-mod src/fo/data/GameTables.hx

Regenerate the .inc files first after a game update (see their generators in
repo/tools/gen_game_names.py and gen_player_icons.py)."""
import re, sys

src, out = sys.argv[1], sys.argv[2]
names = open(src + "/game_names_data.inc", encoding="utf-8").read()
icons = open(src + "/player_icons_data.inc", encoding="utf-8").read()

def block(text, name):
    m = re.search(r"%s\[\] = \{(.*?)\n\};" % name, text, re.S)
    return m.group(1) if m else ""

S = r'"((?:[^"\\]|\\.)*)"'
lines = []
def esc(s):
    s = bytes(s, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")
    assert "|" not in s and "\n" not in s, s
    return s

for m in re.finditer(r"\{%s, %s, TargetRank::(\w+)\}" % (S, S), block(names, "kUnitNames")):
    lines.append("U|%s|%s|%s" % (esc(m[1]), esc(m[2]), m[3]))
for m in re.finditer(r"\{%s, %s\}" % (S, S), block(names, "kItemNames")):
    lines.append("I|%s|%s" % (esc(m[1]), esc(m[2])))
for m in re.finditer(r"\{%s, %s, (\d+), (\d+)\}" % (S, S), block(names, "kTalentNames")):
    lines.append("T|%s|%s|%s|%s" % (esc(m[1]), esc(m[2]), m[3], m[4]))
for m in re.finditer(r"\{%s, (\d+)\}" % S, block(icons, "kClassIcons")):
    lines.append("C|%s|%s" % (esc(m[1]), m[2]))
for m in re.finditer(r"\{%s, (-?\d+), ItemRarity::(\w+)\}" % S, block(icons, "kItemIcons")):
    lines.append("G|%s|%s|%s" % (esc(m[1]), m[2], m[3]))
for m in re.finditer(r"\{%s, %s," % (S, S), block(icons, "kSkillInfos")):
    lines.append("S|%s|%s" % (esc(m[1]), esc(m[2])))
cell = re.search(r"kIconCellPx = (\d+)", icons)[1]
cols = re.search(r"kIconAtlasCols = (\d+)", icons)[1]

counts = {}
for l in lines: counts[l[0]] = counts.get(l[0], 0) + 1
body = "\n".join(lines).replace("\\", "\\\\").replace("'", "\\'").replace("$", "$$")
open(out, "w", encoding="utf-8").write(f"""package fo.data;

// Generated by tools/gen_tables.py from the C++ overlay's game_names_data.inc and
// player_icons_data.inc (themselves generated from data.cdb). Do not edit.
// U unit|name|rank, I item|name, T talent|name|branch|tier, C class|cell,
// G item|cell|rarity, S skill|name.
class GameTables {{
    public static inline var ICON_CELL_PX = {cell};
    public static inline var ICON_ATLAS_COLS = {cols};
    public static inline var COUNTS = "{counts}";
    public static var DATA = '{body}';
}}
""")
print(counts)
